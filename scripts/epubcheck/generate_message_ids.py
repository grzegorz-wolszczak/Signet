#!/usr/bin/env python3
"""Generates MessageId.g.cs, DefaultSeverities.g.cs (Messages/) and FeatureKind.g.cs (Reporting/) of Signet.EpubCheck.Core from a checkout of EPUBCheck.

Usage: generate_message_ids.py <epubcheck-checkout> <Signet.EpubCheck.Core-dir>

The sources are com/adobe/epubcheck/messages/MessageId.java and DefaultSeverities.java of the checkout (the tag
named in src/Signet.EpubCheck.Core/UPSTREAM.md). The order of the ids is the order of the Java enum: the
--listChecks dump follows it.
"""
import re
import sys
from pathlib import Path


def main() -> None:
    root, core = Path(sys.argv[1]), Path(sys.argv[2])
    out = core / "Messages"
    messages = root / "src/main/java/com/adobe/epubcheck/messages"
    ids_src = (messages / "MessageId.java").read_text(encoding="utf-8")
    sev_src = (messages / "DefaultSeverities.java").read_text(encoding="utf-8")

    # NAME("TEXT") or NAME("TEXT", LOCALIZED_ARG.YES), one per enum constant, in declaration order.
    ids = re.findall(r'^\s+([A-Z]{3}_[0-9]{3}[a-z]?)\("([A-Z]{3}[-_][0-9]{3}[a-z]?)"(, LOCALIZED_ARG\.YES)?\)',
                     ids_src, re.M)
    names = [i[0] for i in ids]
    
    for name, text, _ in ids:
        assert name.replace("_", "-") == text.replace("_", "-"), (name, text)
    ids = [(name, name.replace("_", "-"), localized) for name, _, localized in ids]
    assert len(set(names)) == len(names)

    severities = dict(re.findall(r"severities\.put\(MessageId\.([A-Z]{3}_[0-9]{3}[a-z]?), Severity\.([A-Z]+)\)", sev_src))
    assert set(severities) == set(names), set(names) ^ set(severities)

    header = ("// <auto-generated>\n"
              "// Generated by scripts/epubcheck/generate_message_ids.py from EPUBCheck {src}.\n"
              "// Do not edit by hand: change the script or move to another upstream release and generate again.\n"
              "// </auto-generated>\n")

    lines = [header.format(src="com/adobe/epubcheck/messages/MessageId.java"),
             "#pragma warning disable CA1707 // The members keep the names of the upstream constants (OPF_014).\n",
             "namespace Signet.EpubCheck.Core.Messages;\n",
             "/// <summary>The ids of the messages EPUBCheck reports (<c>OPF_014</c> is <c>OPF-014</c>), in the order of upstream's <c>MessageId</c>.</summary>",
             "public enum MessageId",
             "{"]
    lines += [f"    {n}," for n in names]
    lines += ["}", "",
              "/// <summary>The text forms of the <see cref=\"MessageId\"/>s, as upstream prints and parses them.</summary>",
              "public static partial class MessageIds",
              "{",
              "    private static readonly string[] s_texts =",
              "    [",
              ]
    lines += [f'        "{t}",' for _, t, _ in ids]
    lines += ["    ];", "",
              "    // The ids whose first argument is a localized string (upstream's LOCALIZED_ARG.YES).",
              "    private static readonly MessageId[] s_withLocalizedArgument =",
              "    ["]
    lines += [f"        MessageId.{n}," for n, _, loc in ids if loc]
    lines += ["    ];", "}", ""]
    (out / "MessageId.g.cs").write_text("\n".join(lines), encoding="utf-8")

    sev = [header.format(src="com/adobe/epubcheck/messages/DefaultSeverities.java"),
           "namespace Signet.EpubCheck.Core.Messages;\n",
           "public static partial class DefaultSeverities",
           "{",
           "    private static Severity[] Create() =>",
           "    [",
           ]
    sev += [f"        Severity.{severities[n].capitalize()}, // {t}" for n, t, _ in ids]
    sev += ["    ];", "}", ""]
    (out / "DefaultSeverities.g.cs").write_text("\n".join(sev), encoding="utf-8")

    # FeatureEnum: the features of a publication that the reports list (upstream: com/adobe/epubcheck/util/FeatureEnum.java).
    features_src = (root / "src/main/java/com/adobe/epubcheck/util/FeatureEnum.java").read_text(encoding="utf-8")
    features = re.findall(r'^\s+([A-Z0-9_]+)\("([^"]*)"\)[,;]', features_src, re.M)
    pascal = lambda n: "".join(part.capitalize() for part in n.split("_"))
    feat = [header.format(src="com/adobe/epubcheck/util/FeatureEnum.java"),
            "namespace Signet.EpubCheck.Core.Reporting;\n",
            "/// <summary>The features of a publication that the reports list (upstream's <c>FeatureEnum</c>).</summary>",
            "public enum FeatureKind",
            "{"]
    feat += [f"    {pascal(n)}," for n, _ in features]
    feat += ["}", "",
             "/// <summary>The text forms of the <see cref=\"FeatureKind\"/>s, as the reports print them.</summary>",
             "public static partial class FeatureKinds",
             "{",
             "    private static readonly string[] s_texts =",
             "    ["]
    feat += [f'        "{t}",' for _, t in features]
    feat += ["    ];", "}", ""]
    (core / "Reporting").mkdir(exist_ok=True)
    (core / "Reporting" / "FeatureKind.g.cs").write_text("\n".join(feat), encoding="utf-8")
    print(f"{len(ids)} ids, {len(features)} features")


main()
