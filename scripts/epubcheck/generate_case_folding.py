#!/usr/bin/env python3
"""Generates Util/CaseFolding.g.cs of Signet.EpubCheck.Core from the Unicode Character Database.

Usage: generate_case_folding.py <CaseFolding.txt> <Signet.EpubCheck.Core-dir>

Upstream folds case with ICU4J's CaseMap.fold(): full case folding (statuses C and F of CaseFolding.txt), without
the Turkic mappings (status T). .NET has no case folding, so the table is generated. Take CaseFolding.txt of the
Unicode version of the ICU4J release upstream uses (ICU4J 77.1 = Unicode 16.0.0):
https://www.unicode.org/Public/16.0.0/ucd/CaseFolding.txt
"""
import re
import sys
from pathlib import Path


def main() -> None:
    source, core = Path(sys.argv[1]), Path(sys.argv[2])
    text = source.read_text(encoding="utf-8")
    version = re.search(r"^# CaseFolding-([0-9.]+)\.txt", text, re.M)
    assert version, "not a CaseFolding.txt file"

    entries = []
    for line in text.splitlines():
        line = line.split("#", 1)[0].strip()
        if not line:
            continue
        code, status, mapping, _ = [field.strip() for field in line.split(";")]
        if status not in ("C", "F"):
            continue
        entries.append((int(code, 16), [int(c, 16) for c in mapping.split()]))

    codes = [code for code, _ in entries]
    assert len(set(codes)) == len(codes), "a code point has both a C and an F mapping"

    def literal(code_points):
        return '"' + "".join(f"\\U{c:08X}" if c > 0xFFFF else f"\\u{c:04X}" for c in code_points) + '"'

    lines = [
        "// <auto-generated>",
        f"// Generated by scripts/epubcheck/generate_case_folding.py from CaseFolding-{version.group(1)}.txt of the Unicode",
        "// Character Database (full case folding: statuses C and F). Do not edit by hand: generate it again.",
        "// </auto-generated>",
        "",
        "namespace Signet.EpubCheck.Core.Util;",
        "",
        "internal static partial class CaseFolding",
        "{",
        f"    /// <summary>The Unicode version of the table.</summary>",
        f'    public const string UnicodeVersion = "{version.group(1)}";',
        "",
        "    // Code point → its full case folding, in code point order.",
        "    private static readonly (int CodePoint, string Folded)[] s_table =",
        "    [",
    ]
    lines += [f"        (0x{code:04X}, {literal(mapping)})," for code, mapping in entries]
    lines += ["    ];", "}", ""]
    target = core / "Util" / "CaseFolding.g.cs"
    target.write_text("\n".join(lines), encoding="utf-8")
    print(f"{target}: {len(entries)} mappings (Unicode {version.group(1)})")


if __name__ == "__main__":
    main()
