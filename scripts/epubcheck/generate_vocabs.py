#!/usr/bin/env python3
"""Generates Vocab/Vocabularies.g.cs of Signet.EpubCheck.Core from a checkout of EPUBCheck.

Usage: generate_vocabs.py <epubcheck-checkout> <Signet.EpubCheck.Core-dir>

The sources are the vocabulary classes of com/adobe/epubcheck/vocab (the tag named in
src/Signet.EpubCheck.Core/UPSTREAM.md). For every enum of properties the script writes a C# enum (the Java constant
in PascalCase: MARC21XML_RECORD -> Marc21xmlRecord; the enum in the singular: META_PROPERTIES -> MetaProperty) and the table EnumVocab is built from: each member with its
property name and status. The name follows the CaseFormat the Java EnumVocab uses for the enum: LOWER_HYPHEN by
default (ALIGN_X_CENTER -> align-x-center), LOWER_CAMEL where upstream says so (CERTIFIED_BY -> certifiedBy).
The URIs, prefixes and vocabulary instances are written by hand in Vocab/*.cs.
"""
import re
import sys
from pathlib import Path

STATUSES = {"ALLOWED": "Allowed", "DEPRECATED": "Deprecated", "OUTDATED": "Outdated",
            "DISALLOWED_IN_XHTML": "DisallowedInXhtml"}


def pascal(constant: str) -> str:
    return "".join(part[:1].upper() + part[1:].lower() for part in constant.split("_"))


def property_name(constant: str, case_format: str) -> str:
    parts = constant.lower().split("_")
    if case_format == "LOWER_CAMEL":
        return parts[0] + "".join(part[:1].upper() + part[1:] for part in parts[1:])
    assert case_format == "LOWER_HYPHEN", case_format
    return "-".join(parts)


def main() -> None:
    root, core = Path(sys.argv[1]), Path(sys.argv[2])
    source_dir = root / "src/main/java/com/adobe/epubcheck/vocab"
    classes = []
    for path in sorted(source_dir.glob("*.java")):
        text = path.read_text(encoding="utf-8")
        text = re.sub(r"/\*.*?\*/", "", text, flags=re.S)
        text = re.sub(r"//[^\n]*", "", text)
        formats = {}
        for match in re.finditer(r"new EnumVocab<(\w+)>\(\s*\1\.class,\s*(CaseFormat\.(\w+),)?", text):
            formats[match.group(1)] = match.group(3) or "LOWER_HYPHEN"
        enums = []
        for match in re.finditer(r"enum (\w+)(?: implements PropertyStatus\.Holder)?\s*\{(.*?)(;|\})", text, re.S):
            name, body = match.group(1), match.group(2)
            if name not in formats or name == "EMPTY":  # VocabUtil's private empty enum is written by hand
                continue
            members = []
            for constant in re.finditer(r"([A-Z][A-Z0-9_]*)\s*(\(([^)]*)\))?\s*(,|$)", body.strip()):
                args = constant.group(3) or ""
                status = next((s for s in STATUSES if re.fullmatch(r"\s*" + s + r"\s*", args)), "ALLOWED")
                members.append((constant.group(1), status))
            enums.append((name, formats[name], members))
        if enums:
            classes.append((path.stem, enums))

    lines = [
        "// <auto-generated>",
        "// Generated by scripts/epubcheck/generate_vocabs.py from EPUBCheck com/adobe/epubcheck/vocab/*.java.",
        "// Do not edit by hand: change the script or move to another upstream release and generate again.",
        "// </auto-generated>",
        "",
        "namespace Signet.EpubCheck.Core.Vocab;",
        "",
    ]
    count = 0
    for class_name, enums in classes:
        lines += [f"public static partial class {class_name}", "{"]
        for index, (enum_name, case_format, members) in enumerate(enums):
            # Singular, as .NET names enums that are not flags: META_PROPERTIES -> MetaProperty, EPUB_TYPES -> EpubType.
            csharp_enum = pascal(enum_name).replace("Properties", "Property").replace("Types", "Type")
            if index:
                lines.append("")
            lines += [f"    /// <summary>The properties of upstream's <c>{class_name}.{enum_name}</c>.</summary>",
                      f"    public enum {csharp_enum}", "    {"]
            lines += [f"        {pascal(member)}," for member, _ in members]
            lines += ["    }", "",
                      # A property, not a field: the vocabularies built from it are fields of the other part of the
                      # class, and the order of static initializers across the parts of a partial class is not defined.
                      f"    private static (" + csharp_enum + " Property, string Name, PropertyStatus Status)[] "
                      + csharp_enum + "Entries =>",
                      "    ["]
            lines += [f'        ({csharp_enum}.{pascal(member)}, "{property_name(member, case_format)}", PropertyStatus.{STATUSES[status]}),'
                      for member, status in members]
            lines += ["    ];"]
            count += len(members)
        lines += ["}", ""]
    target = core / "Vocab" / "Vocabularies.g.cs"
    target.write_text("\n".join(lines), encoding="utf-8")
    print(f"{target}: {sum(len(e) for _, e in classes)} enums, {count} properties")


if __name__ == "__main__":
    main()
