#!/usr/bin/env python3
"""Generates the vector icons for the menu actions that had none and adds them to the three icon sets.

What it does (see icons_spec.py for the list of icons):
  1. downloads (once, into ./sources) the SVGs the spec names from two npm packages, pinned below:
       - Material Icons, "filled" style (Apache-2.0)  -> the Material set and the shapes of the Default set,
       - Fluent UI System Icons, "regular" 16 px (MIT) -> the Fluent set;
     the same families the existing sets of Signet were made from (the Fluent set and the Material set are copies
     of those icons, the Default set is the colored set of Sigil);
  2. composes them: a base glyph, optionally with a small badge in the bottom-right corner (the base is cut out around
     the badge so it stays readable in a single color), or an existing/new icon three times (a bigger
     one on top, two smaller below it) for the commands that work on more than one file. A base can also be an icon that already
     exists in the sets ('@key');
  3. writes DrawingImage resources between the BEGIN/END markers at the end of
     src/Signet.App/Assets/Icons/{MainIcons,FluentIcons,MaterialIcons}.axaml (everything between the markers is
     replaced on each run, nothing else in those files is touched);
  4. with --catalog, gives the actions of the spec their icon key in src/Signet.App/Actions/AppActionCatalog.cs.

Usage:  python scripts/icons/build_icons.py [--catalog]
"""
import copy
import io
import os
import re
import sys
import urllib.request
import xml.etree.ElementTree as ET

import icons_spec as spec

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, '..', '..'))
ICON_DIR = os.path.join(ROOT, 'src', 'Signet.App', 'Assets', 'Icons')
CATALOG = os.path.join(ROOT, 'src', 'Signet.App', 'Actions', 'AppActionCatalog.cs')

MATERIAL_URL = 'https://cdn.jsdelivr.net/npm/@material-design-icons/svg@0.14.15/filled/{}.svg'
FLUENT_URL = 'https://cdn.jsdelivr.net/npm/@fluentui/svg-icons@1.1.344/icons/{}_16_regular.svg'

BEGIN = '  <!-- BEGIN generated by scripts/icons/build_icons.py (do not edit; run the script) -->'
END = '  <!-- END generated by scripts/icons/build_icons.py -->'

NS_AV = 'https://github.com/avaloniaui'
NS_X = 'http://schemas.microsoft.com/winfx/2006/xaml'
ET.register_namespace('', NS_AV)
ET.register_namespace('x', NS_X)

# Colors. The Fluent and Material sets are single-colored (the accent of the existing sets); the Default set uses the
# colors of its own palette.
ACCENT = '#1abc9c'
MAIN_BASE = '#0ca4d5'
MAIN_ADD = '#1abc9c'
MAIN_REMOVE = '#ea4b4b'
MAIN_OTHER = '#ff7100'
ADD_BADGES = {'add', 'check', 'checkmark', 'done'}
REMOVE_BADGES = {'remove', 'subtract', 'close', 'dismiss', 'delete', 'block', 'prohibited', 'visibility_off', 'eye_off'}

# Layout, as fractions of the canvas.
BASE_WITH_BADGE = 0.78      # size of the base when it has a badge
BADGE_SIZE = 0.50           # size of the badge
HALO = 0.03                 # the gap cut out of the base around the badge
MULTI_MIDDLE = 0.74         # the upper copy of a "more than one file" icon
MULTI_SIDE = 0.50           # the two copies under it, on its sides


def q(tag):
    return '{%s}%s' % (NS_AV, tag)


# ----------------------------------------------------------------------------------------------------------------
# Sources
# ----------------------------------------------------------------------------------------------------------------

_used_sources = set()


def fetch(family, name):
    folder = os.path.join(HERE, 'sources', family)
    os.makedirs(folder, exist_ok=True)
    path = os.path.join(folder, name + '.svg')
    _used_sources.add(os.path.normcase(path))
    if not os.path.exists(path):
        url = (MATERIAL_URL if family == 'material' else FLUENT_URL).format(name)
        print('  downloading', url)
        with urllib.request.urlopen(url, timeout=60) as r:
            data = r.read()
        with open(path, 'wb') as f:
            f.write(data)
    return path


_NUM = re.compile(r'[-+]?(?:\d+\.?\d*|\.\d+)(?:[eE][-+]?\d+)?')
_ARGS = {'M': 2, 'L': 2, 'H': 1, 'V': 1, 'C': 6, 'S': 4, 'Q': 4, 'T': 2, 'A': 7, 'Z': 0}


def normalize_path(d):
    """Re-emits SVG path data as space separated tokens (compact numbers and arc flags split apart)."""
    out = []
    i = 0
    n = len(d)
    cmd = None
    arg_index = 0
    while i < n:
        c = d[i]
        if c in ' ,\t\r\n':
            i += 1
            continue
        if c.isalpha():
            cmd = c
            arg_index = 0
            out.append(c)
            i += 1
            continue
        if cmd is None:
            raise ValueError('path data does not start with a command: ' + d[:30])
        if cmd.upper() == 'A' and arg_index % 7 in (3, 4):
            # arc flags: a single 0/1 character, possibly glued to the next number
            out.append(c)
            i += 1
        else:
            m = _NUM.match(d, i)
            if not m:
                raise ValueError('bad number in path data at %d: %r' % (i, d[i:i + 20]))
            out.append(m.group(0))
            i = m.end()
        arg_index += 1
        if arg_index == _ARGS[cmd.upper()] and cmd.upper() != 'Z':
            arg_index = 0
    return ' '.join(out)


def shape_to_path(el):
    tag = el.tag.split('}')[-1]
    a = el.attrib
    f = lambda k, default=0.0: float(a.get(k, default))
    if tag == 'path':
        return normalize_path(a['d'])
    if tag == 'rect':
        x, y, w, h = f('x'), f('y'), f('width'), f('height')
        return 'M %g %g H %g V %g H %g Z' % (x, y, x + w, y + h, x)
    if tag in ('circle', 'ellipse'):
        cx, cy = f('cx'), f('cy')
        rx = f('r') if tag == 'circle' else f('rx')
        ry = f('r') if tag == 'circle' else f('ry')
        return 'M %g %g A %g %g 0 1 0 %g %g A %g %g 0 1 0 %g %g Z' % (
            cx - rx, cy, rx, ry, cx + rx, cy, rx, ry, cx - rx, cy)
    if tag in ('polygon', 'polyline'):
        nums = [float(x) for x in _NUM.findall(a['points'])]
        pts = list(zip(nums[0::2], nums[1::2]))
        return 'M ' + ' L '.join('%g %g' % p for p in pts) + (' Z' if tag == 'polygon' else '')
    raise ValueError('unsupported SVG element <%s>' % tag)


def load_glyph(family, name):
    """Returns (canvas size, [(path data, fill rule)]) of a source SVG."""
    root = ET.parse(fetch(family, name)).getroot()
    vb = [float(x) for x in re.split(r'[ ,]+', root.attrib['viewBox'].strip())]
    paths = []

    def walk(el):
        if 'transform' in el.attrib:
            raise ValueError('%s/%s: transforms are not supported' % (family, name))
        tag = el.tag.split('}')[-1]
        if tag in ('path', 'rect', 'circle', 'ellipse', 'polygon', 'polyline'):
            style = el.attrib.get('style', '')
            if el.attrib.get('fill') == 'none' or 'fill:none' in style:
                return
            rule = 'evenodd' if (el.attrib.get('fill-rule') == 'evenodd' or 'fill-rule:evenodd' in style) else 'nonzero'
            paths.append((shape_to_path(el), rule))
        for child in el:
            walk(child)

    walk(root)
    if not paths:
        raise ValueError('%s/%s: no shapes' % (family, name))
    return vb[2], paths


# ----------------------------------------------------------------------------------------------------------------
# Existing icons ('@key')
# ----------------------------------------------------------------------------------------------------------------

_existing_cache = {}


def existing_icon(dict_file, key):
    """Returns (canvas size, DrawingGroup element copy) of an icon that is already in a set's dictionary."""
    path = os.path.join(ICON_DIR, dict_file)
    if path not in _existing_cache:
        text = io.open(path, encoding='utf-8').read()
        text = re.sub(re.escape(BEGIN) + '.*?' + re.escape(END), '', text, flags=re.S)
        _existing_cache[path] = ET.fromstring(text)
    for img in _existing_cache[path]:
        if img.attrib.get('{%s}Key' % NS_X) == key:
            group = img.find(q('DrawingImage.Drawing')).find(q('DrawingGroup'))
            m = re.match(r'M 0 0 H ([\d.]+) V ([\d.]+) H 0 Z', group.attrib['ClipGeometry'])
            return float(m.group(1)), copy.deepcopy(group)
    raise KeyError('%s has no icon %s' % (dict_file, key))


# ----------------------------------------------------------------------------------------------------------------
# Composition
# ----------------------------------------------------------------------------------------------------------------

def num(v):
    return ('%.4f' % v).rstrip('0').rstrip('.')


def element(tag, attrib=None, children=()):
    e = ET.Element(q(tag), attrib or {})
    for c in children:
        e.append(c)
    return e


def geometry_drawing(d, rule, color):
    return element('GeometryDrawing', {'Brush': color, 'Geometry': ('F0 ' if rule == 'evenodd' else 'F1 ') + d})


def glyph_group(canvas, paths, color, scale, x, y):
    """The glyph scaled to `scale` of the target canvas, with its top-left corner at (x, y) (target units)."""
    return transformed([geometry_drawing(d, r, color) for d, r in paths], canvas, scale, x, y)


def transformed(children, glyph_canvas, scale_of_target_canvas, x, y, target_canvas=None):
    k = scale_of_target_canvas * (target_canvas or glyph_canvas) / glyph_canvas
    g = element('DrawingGroup')
    t = element('DrawingGroup.Transform')
    t.append(element('MatrixTransform', {'Matrix': '%s,0,0,%s,%s,%s' % (num(k), num(k), num(x), num(y))}))
    g.append(t)
    for c in children:
        g.append(c)
    return g


def clipped(child, canvas, hole):
    """`child` without the rectangle `hole` = (x, y, w, h): an even-odd clip (canvas rectangle + the hole)."""
    hx, hy, hw, hh = hole
    d = 'F0 M 0 0 H %s V %s H 0 Z M %s %s H %s V %s H %s Z' % (
        num(canvas), num(canvas), num(hx), num(hy), num(hx + hw), num(hy + hh), num(hx))
    g = element('DrawingGroup', {'ClipGeometry': d})
    g.append(child)
    return g


def canvas_group(canvas, children):
    box = 'M 0 0 H %s V %s H 0 Z' % (num(canvas), num(canvas))
    g = element('DrawingGroup', {'ClipGeometry': box})
    g.append(element('GeometryDrawing', {'Brush': 'Transparent', 'Geometry': box}))
    for c in children:
        g.append(c)
    return g


def drawing_image(key, canvas, children):
    img = element('DrawingImage')
    img.set('{%s}Key' % NS_X, key)
    drawing = element('DrawingImage.Drawing')
    drawing.append(canvas_group(canvas, children))
    img.append(drawing)
    return img


def badge_color(name):
    return MAIN_ADD if name in ADD_BADGES else MAIN_REMOVE if name in REMOVE_BADGES else MAIN_OTHER


FAMILY_FILES = {'main': 'MainIcons.axaml', 'fluent': 'FluentIcons.axaml', 'material': 'MaterialIcons.axaml'}


def build_icon(key, family):
    """family: 'main' | 'fluent' | 'material'. Returns a DrawingImage element."""
    canvas, children = icon_children(key, family)
    return drawing_image(key, canvas, children)


def source_children(key, family):
    """The drawing of an icon of the spec or of one that already exists in the family's dictionary."""
    if key in spec.ICONS:
        return icon_children(key, family)
    canvas, group = existing_icon(FAMILY_FILES[family], key)
    return canvas, [group]


def icon_children(key, family):
    """Returns (canvas size, drawing elements) of a spec icon in a family."""
    v = spec.ICONS[key]
    if 'multi_of' in v:
        return multi_children(v['multi_of'], family)

    mono = family != 'main'
    gfam = 'fluent' if family == 'fluent' else 'material'
    base_name = v['f'] if family == 'fluent' else v['m']
    badge_name = v['fb'] if family == 'fluent' else v['mb']
    base_color = ACCENT if mono else MAIN_BASE

    # the base: an existing icon or a glyph from the family
    if base_name.startswith('@'):
        canvas, group = existing_icon(FAMILY_FILES[family], base_name[1:])
        place = lambda scale, x, y: transformed([copy.deepcopy(group)], canvas, scale, x, y)
    else:
        canvas, base_paths = load_glyph(gfam, base_name)
        place = lambda scale, x, y: glyph_group(canvas, base_paths, base_color, scale, x, y)

    if not badge_name:
        return canvas, [place(1.0, 0, 0)]

    s = canvas
    bsize = BADGE_SIZE * s
    bx = by = s - bsize
    halo = HALO * s
    hole = (bx - halo, by - halo, bsize + halo, bsize + halo)
    base = clipped(place(BASE_WITH_BADGE, 0, 0), s, hole)
    return canvas, [base, badge_group(canvas, badge_name, family, gfam, mono)]


def multi_children(of, family):
    """`of` (a spec icon or an existing one) as a bigger copy on top of two smaller ones side by side, for the commands
    that work on more than one file."""
    canvas, children = source_children(of, family)

    def place(scale, x, y):
        return transformed([copy.deepcopy(c) for c in children], canvas, scale, x, y)

    s = canvas
    left = place(MULTI_SIDE, 0, 0.5 * s)
    right = place(MULTI_SIDE, (1 - MULTI_SIDE) * s, 0.5 * s)
    return canvas, [left, right, place(MULTI_MIDDLE, (1 - MULTI_MIDDLE) / 2 * s, 0)]


def badge_group(canvas, badge_name, family, gfam, mono):
    gcanvas, paths = load_glyph(gfam, badge_name)
    color = ACCENT if mono else badge_color(badge_name)
    bsize = BADGE_SIZE * canvas
    return transformed([geometry_drawing(d, r, color) for d, r in paths], gcanvas, BADGE_SIZE, canvas - bsize, canvas - bsize,
                       target_canvas=canvas)


# ----------------------------------------------------------------------------------------------------------------
# Output
# ----------------------------------------------------------------------------------------------------------------

def render_block(family):
    root = element('ResourceDictionary')
    for key in sorted(spec.ICONS):
        root.append(build_icon(key, family))
    ET.indent(root, space='  ')
    text = ET.tostring(root, encoding='unicode')
    inner = text[text.index('>') + 1: text.rindex('</')]
    # drop the namespace declarations ElementTree repeats nowhere but the root; indent by one level
    lines = [l for l in inner.split('\n') if l.strip()]
    return '\n'.join(l for l in lines)


def write_dictionary(file_name, family):
    path = os.path.join(ICON_DIR, file_name)
    text = io.open(path, encoding='utf-8', newline='').read()
    crlf = '\r\n' in text
    text = text.replace('\r\n', '\n')
    text = re.sub('\n?' + re.escape(BEGIN) + '.*?' + re.escape(END) + '\n?', '\n', text, flags=re.S)
    close = text.rindex('</ResourceDictionary>')
    block = render_block(family)
    text = text[:close].rstrip('\n') + '\n' + BEGIN + '\n' + block + '\n' + END + '\n' + text[close:]
    if crlf:
        text = text.replace('\n', '\r\n')
    io.open(path, 'w', encoding='utf-8', newline='').write(text)
    print('wrote', file_name, '-', len(spec.ICONS), 'icons')


def prune_sources():
    """Deletes the downloaded SVGs the spec no longer uses."""
    for family in ('material', 'fluent'):
        folder = os.path.join(HERE, 'sources', family)
        for name in os.listdir(folder):
            path = os.path.join(folder, name)
            if name.endswith('.svg') and os.path.normcase(path) not in _used_sources:
                os.remove(path)
                print('removed unused source', family + '/' + name)


def patch_catalog():
    text = io.open(CATALOG, encoding='utf-8', newline='').read()
    count = 0
    for action_id, key in spec.ACTIONS.items():
        pattern = re.compile(r'(new\("%s",\s*"(?:[^"\\]|\\.)*",\s*"[^"]*",\s*)null(,\s*"[^"]*"\))' % re.escape(action_id))
        text, n = pattern.subn(lambda m: m.group(1) + '"%s"' % key + m.group(2), text)
        if n != 1:
            print('  catalog: no `null` icon entry for', action_id, '(already patched?)')
        count += n
    io.open(CATALOG, 'w', encoding='utf-8', newline='').write(text)
    print('catalog: gave an icon to', count, 'actions')


def main():
    os.chdir(HERE)
    write_dictionary('MainIcons.axaml', 'main')
    write_dictionary('FluentIcons.axaml', 'fluent')
    write_dictionary('MaterialIcons.axaml', 'material')
    prune_sources()
    if '--catalog' in sys.argv:
        patch_catalog()


if __name__ == '__main__':
    main()
