    /// <summary>Returns recognized finite keyword alternatives, or <see langword="null"/> when none are catalogued.</summary>
    public static string? ForProperty(string property)
    {
        ArgumentException.ThrowIfNullOrWhiteSpace(property);
        if (Keywords.TryGetValue(property, out string? values))
        {
            return values;
        }

        string unprefixed = StripKnownPrefix(property);
        return Keywords.TryGetValue(unprefixed, out values) ? values : null;
    }

    private static string StripKnownPrefix(string property)
    {
        foreach (string prefix in new[] { "-webkit-", "-moz-", "-ms-", "-epub-" })
        {
            if (property.StartsWith(prefix, StringComparison.OrdinalIgnoreCase))
            {
                return property[prefix.Length..];
            }
        }

        return property;
    }
