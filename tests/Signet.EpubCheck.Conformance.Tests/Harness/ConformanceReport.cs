using System;
using System.Collections.Generic;
using System.Globalization;
using System.IO;
using System.Linq;
using System.Text;
using Signet.EpubCheck.Core;

namespace Signet.EpubCheck.Conformance.Tests.Harness;

/// <summary>How a scenario of upstream's suite ended in a run.</summary>
internal enum ScenarioOutcome
{
    /// <summary>The scenario ran and every step held.</summary>
    Passed,

    /// <summary>The scenario did not run, or stopped at a step the port cannot do yet; the reason says why.</summary>
    Skipped,

    /// <summary>The scenario ran and a step did not hold.</summary>
    Failed,
}

/// <summary>What happened to one scenario.</summary>
/// <param name="Scenario">The scenario.</param>
/// <param name="Outcome">How it ended.</param>
/// <param name="Reason">Why it was skipped, or the first line of what failed; <c>null</c> for a scenario that passed.</param>
internal sealed record ScenarioResult(ScenarioDefinition Scenario, ScenarioOutcome Outcome, string? Reason);

/// <summary>
/// The table of the conformance run (<c>CONFORMANCE.md</c>): per feature how many scenarios passed, were skipped (with the reason)
/// or failed.
/// </summary>
internal static class ConformanceReport
{
    private const int MaxFailureLength = 300;

    /// <summary>Writes the report in Markdown.</summary>
    public static string Render(IReadOnlyCollection<ScenarioResult> results)
    {
        StringBuilder text = new();
        text.Append("# Conformance report\n\n");
        text.Append("The scenarios of EPUBCheck ").Append(EpubCheckVersion.UpstreamRelease).Append("'s own conformance suite, run against the port. ");
        text.Append("Generated by `SIGNET_CONFORMANCE_REPORT=<this file> dotnet test tests/Signet.EpubCheck.Conformance.Tests` ");
        text.Append("(the run of the enabled features; add `SIGNET_CONFORMANCE_ALL=1` to run every scenario).\n\n");

        int passed = results.Count(r => r.Outcome == ScenarioOutcome.Passed);
        int skipped = results.Count(r => r.Outcome == ScenarioOutcome.Skipped);
        int failed = results.Count(r => r.Outcome == ScenarioOutcome.Failed);
        text.Append(CultureInfo.InvariantCulture, $"**{results.Count} scenarios: {passed} passed, {skipped} skipped, {failed} failed.**\n\n");

        text.Append("## Features\n\n| Feature | Passed | Skipped | Failed | Total |\n|---|---:|---:|---:|---:|\n");
        foreach (IGrouping<string, ScenarioResult> feature in results.GroupBy(r => r.Scenario.FeaturePath).OrderBy(g => g.Key, StringComparer.Ordinal))
        {
            text.Append(CultureInfo.InvariantCulture,
                $"| `{feature.Key}` | {feature.Count(r => r.Outcome == ScenarioOutcome.Passed)} | {feature.Count(r => r.Outcome == ScenarioOutcome.Skipped)} | {feature.Count(r => r.Outcome == ScenarioOutcome.Failed)} | {feature.Count()} |\n");
        }

        AppendList(text, "Failed scenarios", results.Where(r => r.Outcome == ScenarioOutcome.Failed));
        AppendSkipped(text, results.Where(r => r.Outcome == ScenarioOutcome.Skipped));
        return text.ToString();
    }

    private static void AppendList(StringBuilder text, string title, IEnumerable<ScenarioResult> results)
    {
        List<ScenarioResult> list = results.OrderBy(r => r.Scenario.Id, StringComparer.Ordinal).ToList();
        if (list.Count == 0)
        {
            return;
        }

        text.Append("\n## ").Append(title).Append("\n\n");
        foreach (ScenarioResult result in list)
        {
            text.Append("- `").Append(result.Scenario.Id).Append("` ").Append(result.Scenario.Name).Append(": ").Append(Shorten(result.Reason)).Append('\n');
        }
    }

    // The skipped scenarios, a heading per reason (the reasons are few; the scenarios under one are many).
    private static void AppendSkipped(StringBuilder text, IEnumerable<ScenarioResult> skipped)
    {
        List<IGrouping<string, ScenarioResult>> groups = skipped.GroupBy(r => r.Reason ?? "No reason given").OrderByDescending(g => g.Count()).ThenBy(g => g.Key, StringComparer.Ordinal).ToList();
        if (groups.Count == 0)
        {
            return;
        }

        text.Append("\n## Skipped scenarios\n");
        foreach (IGrouping<string, ScenarioResult> group in groups)
        {
            text.Append(CultureInfo.InvariantCulture, $"\n### {Shorten(group.Key)} ({group.Count()})\n\n");
            foreach (IGrouping<string, ScenarioResult> feature in group.GroupBy(r => r.Scenario.FeaturePath).OrderBy(g => g.Key, StringComparer.Ordinal))
            {
                text.Append("- `").Append(feature.Key).Append("`: ")
                    .Append(string.Join(", ", feature.Select(r => r.Scenario.Line).Order().Select(l => l.ToString(CultureInfo.InvariantCulture)))).Append('\n');
            }
        }
    }

    private static string Shorten(string? reason)
    {
        string line = (reason ?? string.Empty).ReplaceLineEndings(" ").Trim();
        return line.Length <= MaxFailureLength ? line : line[..MaxFailureLength] + "…";
    }
}

/// <summary>Collects what happened to each scenario of the run, for the report.</summary>
internal static class ScenarioOutcomes
{
    private static readonly object s_lock = new();
    private static readonly Dictionary<string, ScenarioResult> s_results = new(StringComparer.Ordinal);

    public static void Record(ScenarioDefinition scenario, ScenarioOutcome outcome, string? reason = null)
    {
        lock (s_lock)
        {
            s_results[scenario.Id] = new ScenarioResult(scenario, outcome, reason);
        }
    }

    /// <summary>Every scenario of the suite: the ones that ran with what happened, the others as skipped with the reason they were not run.</summary>
    public static IReadOnlyList<ScenarioResult> All(IReadOnlyList<ScenarioDefinition> scenarios, string notEnabledReason)
    {
        lock (s_lock)
        {
            return scenarios.Select(s => s_results.TryGetValue(s.Id, out ScenarioResult? ran)
                ? ran
                : new ScenarioResult(
                    s,
                    ScenarioOutcome.Skipped,
                    ConformanceCorpus.PendingScenarios.TryGetValue(s.Id, out string? reason) ? reason : notEnabledReason)).ToList();
        }
    }
}

/// <summary>
/// Writes the conformance report at the end of the run when <c>SIGNET_CONFORMANCE_REPORT</c> names a file (an assembly fixture,
/// so it is disposed after the last test).
/// </summary>
public sealed class ConformanceReportWriter : IDisposable
{
    /// <summary>The environment variable that names the file the report is written to.</summary>
    internal const string FileVariable = "SIGNET_CONFORMANCE_REPORT";

    /// <inheritdoc />
    public void Dispose()
    {
        string? file = Environment.GetEnvironmentVariable(FileVariable);
        if (string.IsNullOrWhiteSpace(file))
        {
            return;
        }

        IReadOnlyList<ScenarioDefinition> scenarios = FeatureLoader.LoadAll(ConformanceCorpus.Root);
        File.WriteAllText(file, ConformanceReport.Render(ScenarioOutcomes.All(scenarios, Tests.UpstreamScenarioTests.NotEnabled)), new UTF8Encoding(false));
    }
}
